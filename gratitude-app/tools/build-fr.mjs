// Builds js/i18n/fr.js from tools/fr-ui.mjs and tools/fr-content.mjs.
// Run: node tools/build-fr.mjs   (fails loudly if any list is out of step with the English)
import { writeFileSync } from 'node:fs';
import UI from './fr-ui.mjs';
import * as FR from './fr-content.mjs';

const imp = (p) => import(new URL(`../js/${p}`, import.meta.url));
const prompts = await imp('prompts.js');
const stats = await imp('stats.js');
const ch = await imp('challenges.js');
const sounds = await imp('sounds.js');
const card = await imp('sharecard.js');
const sched = await imp('schedule.js');
const pause = await imp('pause.js');

const dict = {};
const errors = [];
function put(en, fr, where) {
  if (!en) return;
  if (!fr) return errors.push(`Missing French for ${where}: ${en}`);
  if (dict[en] && dict[en] !== fr) errors.push(`Conflicting translations for "${en}": "${dict[en]}" vs "${fr}"`);
  dict[en] = fr;
}
function zip(enList, frList, where) {
  if (enList.length !== frList.length) errors.push(`${where}: ${enList.length} English vs ${frList.length} French`);
  enList.forEach((en, i) => put(en, frList[i], `${where}[${i}]`));
}

for (const [id, c] of Object.entries(prompts.CATEGORIES)) {
  const f = FR.CATEGORIES[id];
  if (!f) errors.push(`Category ${id} missing`);
  put(c.label, f?.label, `category ${id}`);
  if (c.chip) put(c.chip, f?.chip, `chip ${id}`);
}
const byCat = {};
for (const p of prompts.PROMPTS) (byCat[p.category] ??= []).push(p.text);
for (const [id, list] of Object.entries(byCat)) zip(list, FR.PROMPTS[id] || [], `prompts.${id}`);
for (const [id, list] of Object.entries(prompts.WORD_IDEAS)) zip(list, FR.WORD_IDEAS[id] || [], `words.${id}`);
zip(prompts.wordIdeasFor(null), FR.GENERAL_IDEAS, 'general ideas');
zip(prompts.POSITIVE_MESSAGES, FR.POSITIVE_MESSAGES, 'positive messages');
zip(prompts.SAVE_ACKNOWLEDGEMENTS, FR.SAVE_ACKNOWLEDGEMENTS, 'acknowledgements');
zip(stats.MOODS.map((m) => m.label), FR.MOODS, 'moods');
zip(stats.MILESTONES.map((m) => m.label), FR.MILESTONES, 'milestones');
zip(ch.CHALLENGES.map((c) => c.title), FR.CHALLENGES.map((c) => c.title), 'challenge titles');
zip(ch.CHALLENGES.map((c) => c.tagline), FR.CHALLENGES.map((c) => c.tagline), 'challenge taglines');
zip(ch.DAY_PLAN.map((d) => d.prompt), FR.DAY_PLAN, 'day plan');
zip(pause.PAUSE_STEPS, FR.PAUSE_STEPS, 'pause steps');
zip(sounds.BELL_SOUNDS.map((b) => b.label), FR.BELL_SOUNDS.map((b) => b.label), 'bell labels');
zip(sounds.BELL_SOUNDS.map((b) => b.desc), FR.BELL_SOUNDS.map((b) => b.desc), 'bell descriptions');
zip(card.CARD_STYLES.map((c) => c.label), FR.CARD_STYLES, 'card styles');
zip(sounds.BELL_VOLUMES.map((v) => v.label), FR.BELL_VOLUMES, 'bell volumes');
zip(sounds.BELL_REPEATS.map((r) => r.label), FR.BELL_REPEATS, 'bell repeats');
zip(sched.FREQUENCY_OPTIONS.map((o) => o.label), FR.FREQUENCY.map((o) => o.label), 'frequency');
zip(sched.FREQUENCY_OPTIONS.map((o) => o.short), FR.FREQUENCY.map((o) => o.short), 'frequency short');
for (const [en, fr] of Object.entries(FR.MESSAGES)) put(en, fr, 'messages');
for (const [en, fr] of Object.entries(UI)) put(en, fr, 'ui');

// French typography: non-breaking space before ? ! : ; and inside « »
const nbsp = ' ';
for (const k of Object.keys(dict)) {
  dict[k] = dict[k]
    .replace(/ ([?!:;])/g, `${nbsp}$1`)
    .replace(/« /g, `«${nbsp}`)
    .replace(/ »/g, `${nbsp}»`);
}

// Completeness check against every string the app shows.
const { allKeys } = await import('./i18n-keys.mjs');
const { keys, plurals } = await allKeys();
for (const k of keys) if (!(k in dict)) errors.push(`Not translated: ${k}`);
for (const k of plurals) if (!(`${k}#other` in dict)) errors.push(`Missing plural: ${k}#other`);

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}
const sorted = Object.fromEntries(Object.entries(dict).sort(([a], [b]) => a.localeCompare(b)));
const out = `// French translations. GENERATED by tools/build-fr.mjs from tools/fr-ui.mjs and tools/fr-content.mjs.
// Edit those files, then run: node tools/build-fr.mjs
export default ${JSON.stringify(sorted, null, 2)};
`;
writeFileSync(new URL('../js/i18n/fr.js', import.meta.url), out);
console.log(`Wrote ${Object.keys(sorted).length} French translations.`);
